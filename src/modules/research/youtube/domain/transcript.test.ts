import { describe, expect, it } from "vitest";
import {
  cleanCaptionText,
  formatTimestamp,
  formatTranscriptPage,
  type VideoTranscript,
} from "./transcript";
import type { YouTubeVideoId } from "./video-id";

function sampleTranscript(segmentCount: number): VideoTranscript {
  return {
    videoId: "dQw4w9WgXcQ" as YouTubeVideoId,
    url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
    title: "Henzie Toolbox Torre Deck Tech",
    channel: "Commander Channel",
    durationSec: segmentCount * 5,
    language: "en",
    isAutoGenerated: false,
    segments: Array.from({ length: segmentCount }, (_, i) => ({
      text: `Segment ${i}: Henzie blitzes out big creatures for value.`,
      startSec: i * 5,
      durationSec: 5,
    })),
  };
}

describe("formatTimestamp & cleanCaptionText", () => {
  it("formats MM:SS and HH:MM:SS timestamps", () => {
    expect(formatTimestamp(0)).toBe("00:00");
    expect(formatTimestamp(65)).toBe("01:05");
    expect(formatTimestamp(3661)).toBe("1:01:01");
  });

  it("decodes HTML entities and collapses whitespace", () => {
    expect(cleanCaptionText("Sol Ring &amp;  Arcane &#39;Signet&#39;\n  FTW")).toBe(
      "Sol Ring & Arcane 'Signet' FTW",
    );
  });
});

describe("formatTranscriptPage", () => {
  it("defaults to plain text without timestamps", () => {
    const page = formatTranscriptPage(sampleTranscript(2));
    expect(page.text).toBe(
      "Segment 0: Henzie blitzes out big creatures for value. Segment 1: Henzie blitzes out big creatures for value.",
    );
    expect(page.nextCursor).toBeUndefined();
    expect(page.returnedSegments).toBe(2);
  });

  it("includes [MM:SS] timestamps when includeTimestamps is true", () => {
    const page = formatTranscriptPage(sampleTranscript(2), { includeTimestamps: true });
    expect(page.text).toBe(
      "[00:00] Segment 0: Henzie blitzes out big creatures for value.\n[00:05] Segment 1: Henzie blitzes out big creatures for value.",
    );
  });

  it("pages across all segments without gaps or duplicates under a tight byte cap", () => {
    const transcript = sampleTranscript(25);
    const collected: string[] = [];
    let cursor: number | undefined = 0;

    while (cursor !== undefined) {
      const page = formatTranscriptPage(transcript, {
        includeTimestamps: true,
        cursor,
        maxBytes: 220,
      });
      expect(new TextEncoder().encode(page.text).length).toBeLessThanOrEqual(220);
      collected.push(...page.text.split("\n"));
      cursor = page.nextCursor;
    }

    expect(collected).toHaveLength(25);
    expect(collected[0]).toContain("Segment 0:");
    expect(collected[24]).toContain("Segment 24:");
  });
});
