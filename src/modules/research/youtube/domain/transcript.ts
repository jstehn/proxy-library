import type { YouTubeVideoId } from "./video-id";

export type TranscriptSegment = Readonly<{
  text: string;
  startSec: number;
  durationSec: number;
}>;

export type VideoTranscript = Readonly<{
  videoId: YouTubeVideoId;
  url: string;
  title: string;
  channel: string;
  durationSec: number | null;
  language: string;
  isAutoGenerated: boolean;
  segments: readonly TranscriptSegment[];
}>;

export type FormattedTranscriptPage = Readonly<{
  text: string;
  cursor: number;
  nextCursor?: number;
  returnedSegments: number;
  totalSegments: number;
}>;

const DEFAULT_MAX_BYTES = 32_000;
const textEncoder = new TextEncoder();

function utf8Bytes(value: string): number {
  return textEncoder.encode(value).length;
}

export function formatTimestamp(totalSeconds: number): string {
  const clamped = Math.max(0, Math.floor(totalSeconds));
  const hours = Math.floor(clamped / 3600);
  const minutes = Math.floor((clamped % 3600) / 60);
  const seconds = clamped % 60;
  const mm = String(minutes).padStart(2, "0");
  const ss = String(seconds).padStart(2, "0");
  return hours > 0 ? `${hours}:${mm}:${ss}` : `${mm}:${ss}`;
}

export function cleanCaptionText(raw: string): string {
  return raw
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'")
    .replaceAll("&apos;", "'")
    .replaceAll("&nbsp;", " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Formats a slice of transcript segments starting at `cursor` into plain text or `[MM:SS]` lines,
 * fitting strictly within `maxBytes` without splitting mid-segment.
 */
export function formatTranscriptPage(
  transcript: VideoTranscript,
  options: {
    includeTimestamps?: boolean;
    cursor?: number;
    maxBytes?: number;
  } = {},
): FormattedTranscriptPage {
  const includeTimestamps = options.includeTimestamps ?? false;
  const maxBytes = options.maxBytes ?? DEFAULT_MAX_BYTES;
  const totalSegments = transcript.segments.length;
  const start =
    options.cursor !== undefined && Number.isInteger(options.cursor) && options.cursor >= 0
      ? Math.min(options.cursor, totalSegments)
      : 0;

  if (start >= totalSegments) {
    return {
      text: "",
      cursor: start,
      returnedSegments: 0,
      totalSegments,
    };
  }

  const separator = includeTimestamps ? "\n" : " ";
  const sepBytes = utf8Bytes(separator);
  const lines: string[] = [];
  let usedBytes = 0;
  let index = start;

  while (index < totalSegments) {
    const seg = transcript.segments[index];
    if (!seg) {
      index += 1;
      continue;
    }
    const cleaned = cleanCaptionText(seg.text);
    if (cleaned.length === 0) {
      index += 1;
      continue;
    }

    const formatted = includeTimestamps ? `[${formatTimestamp(seg.startSec)}] ${cleaned}` : cleaned;
    const pieceBytes = utf8Bytes(formatted) + (lines.length > 0 ? sepBytes : 0);

    if (lines.length > 0 && usedBytes + pieceBytes > maxBytes) {
      break;
    }

    // Even if the very first segment exceeds maxBytes on its own, include it so progress is guaranteed.
    lines.push(formatted);
    usedBytes += pieceBytes;
    index += 1;
  }

  return {
    text: lines.join(separator),
    cursor: start,
    ...(index < totalSegments ? { nextCursor: index } : {}),
    returnedSegments: index - start,
    totalSegments,
  };
}
