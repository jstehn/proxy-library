import { ok, type Result } from "@/shared/kernel";
import {
  buildDeckTechQuery,
  formatTranscriptPage,
  parseYouTubeVideoId,
  rankAndFilterSearchResults,
  type DeckTechSearchKind,
  type SearchSortMode,
  type YouTubeSearchResult,
  type YouTubeVideoId,
} from "../domain";
import type { YouTubeError, YouTubeGateway } from "./ports";

export type SearchDeckTechsOutput = Readonly<{
  queryUsed: string;
  results: readonly YouTubeSearchResult[];
}>;

export type GetTranscriptOutput = Readonly<{
  videoId: YouTubeVideoId;
  url: string;
  title: string;
  channel: string;
  durationSec: number | null;
  language: string;
  isAutoGenerated: boolean;
  includeTimestamps: boolean;
  transcript: string;
  cursor: number;
  nextCursor?: number;
  returnedSegments: number;
  totalSegments: number;
}>;

const DEFAULT_SEARCH_LIMIT = 8;
const MAX_SEARCH_LIMIT = 15;

export function makeYoutube(deps: { gateway: YouTubeGateway }) {
  return {
    async searchDeckTechs(input: {
      query: string;
      kind?: DeckTechSearchKind;
      sortBy?: SearchSortMode;
      minDurationSec?: number;
      limit?: number;
    }): Promise<Result<SearchDeckTechsOutput, YouTubeError>> {
      const kind = input.kind ?? "deck_tech";
      const sortBy = input.sortBy ?? "balanced";
      const shaped = buildDeckTechQuery(input.query, kind);
      if (!shaped.ok) return shaped;

      const rawLimit = input.limit ?? DEFAULT_SEARCH_LIMIT;
      const limit = Math.max(1, Math.min(MAX_SEARCH_LIMIT, Math.floor(rawLimit)));
      const candidateLimit = Math.min(25, Math.max(limit * 3, 20));

      const found = await deps.gateway.searchVideos({
        query: shaped.value,
        limit: candidateLimit,
      });
      if (!found.ok) return found;

      const ranked = rankAndFilterSearchResults(found.value, {
        kind,
        sortBy,
        limit,
        minDurationSec: input.minDurationSec,
      });

      return ok({
        queryUsed: shaped.value,
        results: ranked,
      });
    },

    async getTranscript(input: {
      video: string;
      lang?: string;
      includeTimestamps?: boolean;
      cursor?: number;
      maxBytes?: number;
    }): Promise<Result<GetTranscriptOutput, YouTubeError>> {
      const parsedId = parseYouTubeVideoId(input.video);
      if (!parsedId.ok) return parsedId;

      const lang = (input.lang ?? "en").trim().toLowerCase() || "en";
      const fetched = await deps.gateway.fetchTranscript({ videoId: parsedId.value, lang });
      if (!fetched.ok) return fetched;

      const includeTimestamps = input.includeTimestamps ?? false;
      const page = formatTranscriptPage(fetched.value, {
        includeTimestamps,
        cursor: input.cursor,
        maxBytes: input.maxBytes,
      });

      return ok({
        videoId: fetched.value.videoId,
        url: fetched.value.url,
        title: fetched.value.title,
        channel: fetched.value.channel,
        durationSec: fetched.value.durationSec,
        language: fetched.value.language,
        isAutoGenerated: fetched.value.isAutoGenerated,
        includeTimestamps,
        transcript: page.text,
        cursor: page.cursor,
        ...(page.nextCursor !== undefined ? { nextCursor: page.nextCursor } : {}),
        returnedSegments: page.returnedSegments,
        totalSegments: page.totalSegments,
      });
    },
  };
}

export type YoutubeService = ReturnType<typeof makeYoutube>;
