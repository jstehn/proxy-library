import { describe, expect, it } from "vitest";
import { err, ok } from "@/shared/kernel";
import type { YouTubeVideoId } from "../domain";
import type { YouTubeGateway } from "./ports";
import { makeYoutube } from "./use-cases";

function fakeGateway(): YouTubeGateway {
  return {
    async searchVideos({ query, limit }) {
      return ok([
        {
          videoId: "dQw4w9WgXcQ" as YouTubeVideoId,
          url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
          title: `Result for ${query} (limit ${limit})`,
          channel: "Deck Tech TV",
          durationSec: 900,
          durationText: "15:00",
          publishedText: "2 weeks ago",
          viewCountText: "12K views",
        },
      ]);
    },
    async fetchTranscript({ videoId, lang }) {
      if (videoId === ("missing0000" as YouTubeVideoId)) {
        return err({ kind: "TranscriptUnavailable", message: "No captions." });
      }
      return ok({
        videoId,
        url: `https://www.youtube.com/watch?v=${videoId}`,
        title: "Henzie Deck Tech",
        channel: "Deck Tech TV",
        durationSec: 600,
        language: lang,
        isAutoGenerated: false,
        segments: [
          { text: "Welcome to the Henzie deck tech.", startSec: 0, durationSec: 4 },
          { text: "First up is Protean Hulk.", startSec: 4, durationSec: 4 },
        ],
      });
    },
  };
}

describe("makeYoutube use cases", () => {
  it("shapes deck-tech search queries and clamps limit", async () => {
    const service = makeYoutube({ gateway: fakeGateway() });
    const res = await service.searchDeckTechs({ query: "Henzie", limit: 99 });

    expect(res.ok).toBe(true);
    if (res.ok) {
      expect(res.value.queryUsed).toBe("Henzie MTG Commander deck tech");
      expect(res.value.results[0]?.title).toContain("limit 25");
    }
  });

  it("parses URLs, defaults includeTimestamps to false, and returns transcript metadata", async () => {
    const service = makeYoutube({ gateway: fakeGateway() });
    const res = await service.getTranscript({
      video: "https://youtu.be/dQw4w9WgXcQ",
    });

    expect(res.ok).toBe(true);
    if (res.ok) {
      expect(res.value.includeTimestamps).toBe(false);
      expect(res.value.transcript).toBe(
        "Welcome to the Henzie deck tech. First up is Protean Hulk.",
      );
      expect(res.value.totalSegments).toBe(2);
    }
  });

  it("returns TranscriptUnavailable when gateway has no captions", async () => {
    const service = makeYoutube({ gateway: fakeGateway() });
    const res = await service.getTranscript({ video: "missing0000" });

    expect(res.ok).toBe(false);
    if (!res.ok) {
      expect(res.error.kind).toBe("TranscriptUnavailable");
    }
  });
});
